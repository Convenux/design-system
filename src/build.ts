/* -- the contract ---------------------------------------------------------- */

function audit(): { failures: string[]; rows: string[] } {
  const failures: string[] = [];
  const rows: string[] = [];

  for (const pair of contrastContract) {
    const fg = color[pair.fg as ColorName] as Hex;
    const bg = color[pair.bg as ColorName] as Hex;
    const got = Number(report(fg, bg));
    const ok = got >= pair.min;
    rows.push(
      `${ok ? "  ok " : "FAIL"} ${pair.fg.padEnd(11)} on ${pair.bg.padEnd(11)} ${String(
        got,
      ).padStart(5)}:1  (needs ${pair.min}) — ${pair.note}`,
    );
    if (!ok) {
      failures.push(
        `${pair.fg} on ${pair.bg} is ${got}:1, below the ${pair.min}:1 this pair needs (${pair.note}).`,
      );
    }
  }
  return { failures, rows };
}

