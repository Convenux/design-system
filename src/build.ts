/** A Tailwind v4 `@theme` block. The `--font-*` variables come from each app's next/font. */
function css(): string {
  const l = (s = "") => lines.push(s);
  const lines: string[] = [];

  l(`/*\n${BANNER}\n*/`);
  l();
  l("@theme {");

  l("  /* Type. `--font-manrope` and `--font-jetbrains-mono` come from next/font. */");
  l("  /* Each var() has its own fallback: an unset one would void the whole stack. */");
  l(
    `  --font-display: var(--font-manrope, ${font.display.stack[0]}), ${font.display.stack.join(", ")};`,
  );
  l(
    `  --font-sans: var(--font-manrope, ${font.sans.stack[0]}), ${font.sans.stack.join(", ")};`,
  );
  l(
    `  --font-mono: var(--font-jetbrains-mono, ${font.mono.stack[0]}), ${font.mono.stack.join(", ")};`,
  );
  l();

  l("  /* Surfaces, darkest first. A card on a card steps up, never down. */");
  for (const name of ["ink", "ink-2", "ink-3", "ink-4", "ink-5"] as const) {
    l(`  --color-${name}: ${color[name]};`);
  }
  l();

  l("  /* Hairlines are decorative (1.4.11 exempt). Controls use --color-control. */");
  for (const name of ["line-subtle", "line", "line-strong", "control"] as const) {
    l(`  --color-${name}: ${color[name]};`);
  }
  l();

  l("  /* Text, brightest first. fg-6 is the floor; there is deliberately no fg-7. */");
  for (const name of ["fg", "fg-2", "fg-3", "fg-4", "fg-5", "fg-6"] as const) {
    l(`  --color-${name}: ${color[name]};`);
  }
  l();

  l("  /* Violet — the one brand colour. */");
  for (const name of [
    "violet-300",
    "violet-400",
    "violet-500",
    "violet-600",
    "violet-tint",
    "violet-edge",
    "on-violet",
  ] as const) {
    l(`  --color-${name}: ${color[name]};`);
  }
  l();

  l("  /* Signals. Named for the hue; the meaning belongs to the component. */");
  for (const name of [
    "mint-400",
    "mint-tint",
    "mint-edge",
    "amber-400",
    "amber-tint",
    "amber-edge",
    "rose-400",
    "rose-tint",
    "rose-edge",
  ] as const) {
    l(`  --color-${name}: ${color[name]};`);
  }
  l();

  l("  /* A badge, a control, a field, a panel, a card, a pill. */");
  for (const [name, px] of Object.entries(radius)) {
    l(`  --radius-${name}: ${px}px;`);
  }
  l();

  l("  /* Chrome: the bar, the page width, the two control heights. */");
  l(`  --spacing-bar: ${chrome.bar.height}px;`);
  l(`  --container-shell: ${chrome.shell.reading}px;`);
  l(`  --container-shell-wide: ${chrome.shell.wide}px;`);
  l(`  --spacing-control-sm: ${chrome.control.sm}px;`);
  l(`  --spacing-control-md: ${chrome.control.md}px;`);
  l();

  l("  /* Easings. Keyframes stay in each app — see tokens.ts. */");
  l(`  --ease-snap: ${motion["ease-snap"]};`);
  l(`  --ease-flow: ${motion["ease-flow"]};`);
  for (const [name, ms] of Object.entries(motion.duration)) {
    l(`  --duration-${name}: ${ms}ms;`);
  }
  l();

  l("  /* The type scale. */");
  for (const [name, { size, leading }] of Object.entries(text)) {
    l(`  --text-${name}: ${size}px;`);
    l(`  --text-${name}--line-height: ${leading};`);
  }

  l("}");
  l();
  return lines.join("\n");
}

