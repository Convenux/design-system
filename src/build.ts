/* -- native.js and native.d.ts --------------------------------------------- */

/**
 * React Native gets plain values. One family per weight rather than a `fontWeight`:
 * Android picks the wrong file once a family ships more than two faces.
 */
const MANROPE_FACES: Record<number, string> = {
  400: "Regular",
  500: "Medium",
  600: "SemiBold",
  700: "Bold",
  800: "ExtraBold",
};

const MONO_FACES: Record<number, string> = {
  400: "Regular",
  500: "Medium",
  600: "SemiBold",
  700: "Bold",
};

const faces = (
  weights: readonly number[],
  exportPrefix: string,
  names: Record<number, string>,
) => weights.map((w) => `    ${w}: "${exportPrefix}_${w}${names[w]}",`).join("\n");

/** The shared object literals, identical in the runtime and the declarations. */
function nativeData(): Record<string, string> {
  return {
    color: Object.entries(color)
      .map(([name, hex]) => `  "${name}": "${hex}",`)
      .join("\n"),
    radius: Object.entries(radius)
      .map(([name, px]) => `  ${name}: ${px},`)
      .join("\n"),
    space: Object.entries(space)
      .map(([step, px]) => `  "${step}": ${px},`)
      .join("\n"),
    text: Object.entries(text)
      .map(
        ([name, { size, leading }]) =>
          `  "${name}": { fontSize: ${size}, lineHeight: ${Math.round(size * leading)} },`,
      )
      .join("\n"),
    duration: Object.entries(motion.duration)
      .map(([name, ms]) => `  ${name}: ${ms},`)
      .join("\n"),
    markSizes: Object.entries(chrome.mark)
      .map(
        ([k, v]) =>
          `    ${k}: { icon: ${v.icon}, iconRadius: ${v.iconRadius}, name: ${v.name}, gap: ${v.gap} },`,
      )
      .join("\n"),
  };
}

